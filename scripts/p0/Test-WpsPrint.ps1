#requires -Version 5.1
<#
.SYNOPSIS
    P0: print a real WPS Writer document to the PrintPal IPP probe.

.DESCRIPTION
    The PrintProbe covers the GDI path; this script covers the actual WPS Writer
    path that the product must support. It creates a 3-page document, switches
    WPS to the PrintPal queue, prints with the requested copy count, and lets the
    IPP probe record what WPS actually sent.

    WPS Writer exposes a Word-compatible COM object (KWps.Application). PrintOut
    is invoked through reflection because PowerShell's COM binder handles the
    many optional by-ref parameters poorly.

    This script does not change the system default printer unless ActivePrinter
    is rejected; in that case it restores the previous default in finally.
#>
[CmdletBinding()]
param(
    [int] $Pages = 3,
    [int] $Copies = 2,
    [string] $Printer = 'PrintPal 虚拟打印机',
    [string] $LogPath = 'C:\Develop\code\AGI\PrintPal\artifacts\p0\wps-print.log'
)

$ErrorActionPreference = 'Stop'
New-Item -ItemType Directory -Force -Path (Split-Path -Parent $LogPath) | Out-Null
Start-Transcript -Path $LogPath -Force | Out-Null

$app = $null
$doc = $null
$originalDefault = $null

try {
    Write-Host "=== WPS print test $(Get-Date -Format o) ==="
    Write-Host "Printer: $Printer  Pages: $Pages  Copies: $Copies"

    $app = New-Object -ComObject KWps.Application
    $app.Visible = $false
    try { $app.DisplayAlerts = 0 } catch { }

    $doc = $app.Documents.Add()

    # Build N pages. wdPageBreak = 7.
    for ($i = 1; $i -le $Pages; $i++) {
        $app.Selection.TypeText("PrintPal P0 WPS test page $i of $Pages")
        $app.Selection.TypeParagraph()
        $app.Selection.TypeText("Generated by Test-WpsPrint.ps1 at $(Get-Date -Format o)")
        if ($i -lt $Pages) {
            $app.Selection.InsertBreak(7)
        }
    }

    # Prefer the app-level printer so the system default is untouched.
    $activeSet = $false
    try {
        $app.ActivePrinter = $Printer
        $activeSet = $true
        Write-Host "WPS ActivePrinter set to '$($app.ActivePrinter)'"
    } catch {
        Write-Warning "ActivePrinter failed: $($_.Exception.Message); switching system default temporarily."
        $current = Get-CimInstance Win32_Printer | Where-Object { $_.Default -eq $true } | Select-Object -First 1
        $originalDefault = $current
        $target = Get-CimInstance Win32_Printer -Filter "Name='$Printer'"
        if (-not $target) { throw "Printer '$Printer' not found." }
        $target.SetDefaultPrinter() | Out-Null
        Write-Host "System default printer changed to '$Printer'."
    }

    try { $app.Options.PrintBackground = $false } catch { }

    # Word-compatible PrintOut signature (18 optional args). Copies is index 7.
    $missing = [System.Type]::Missing
    $args = @(
        $false,      # Background
        $false,      # Append
        0,           # Range (wdPrintAllDocument)
        '',          # OutputFileName
        0,           # From
        0,           # To
        0,           # Item (wdPrintDocumentContent)
        [int]$Copies,# Copies
        $missing,    # Pages
        $missing,    # PageType
        $missing,    # PrintToFile
        $missing,    # Collate
        $missing,    # ActivePrinterMacGX
        $missing,    # ManualDuplexPrint
        $missing,    # PrintZoomColumn
        $missing,    # PrintZoomRow
        $missing,    # PrintZoomPaperWidth
        $missing     # PrintZoomPaperHeight
    )

    Write-Host "Calling Document.PrintOut(Copies=$Copies) ..."
    $doc.GetType().InvokeMember(
        'PrintOut',
        [System.Reflection.BindingFlags]::InvokeMethod,
        $null,
        $doc,
        $args
    ) | Out-Null

    Write-Host "PrintOut returned."
    Start-Sleep -Seconds 5
}
catch {
    Write-Host "FAILED: $($_.Exception.Message)" -ForegroundColor Red
    Write-Host $_.ScriptStackTrace
}
finally {
    try { if ($doc) { $doc.Close(0) } } catch { }
    try { if ($app) { $app.Quit() } } catch { }
    try { if ($app) { [System.Runtime.InteropServices.Marshal]::ReleaseComObject($app) | Out-Null } } catch { }

    if ($originalDefault) {
        try {
            $originalDefault.SetDefaultPrinter() | Out-Null
            Write-Host "Restored default printer to '$($originalDefault.Name)'."
        } catch {
            Write-Warning "Could not restore default printer: $($_.Exception.Message)"
        }
    }

    Stop-Transcript | Out-Null
}

exit 0
